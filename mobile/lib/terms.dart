/// Vernacular astrology terms with the English name in brackets.
///
/// English stays unchanged. Hindi and Marathi lead with the local word.
String astroTerm(String languageCode, dynamic value) {
  final text = value == null ? '' : value.toString();
  if (text.isEmpty) return '—';
  if (!languageCode.startsWith('hi') && !languageCode.startsWith('mr')) {
    return text;
  }
  final local = _lexicon(languageCode)[text];
  if (local == null) return text;
  return '$local ($text)';
}

Map<String, String> _lexicon(String languageCode) {
  final hindi = languageCode.startsWith('hi');
  return {
    ..._pairs(_signs, hindi ? _hiSigns : _mrSigns),
    ..._pairs(_nakshatras, hindi ? _hiNakshatras : _mrNakshatras),
    ..._pairs(_tithis, _tithiLocal),
    ..._pairs(_yogas, _yogaLocal),
    ..._karanas,
    ..._pairs(_planets, hindi ? _hiPlanets : _mrPlanets),
    ..._pairs(_weekdays, hindi ? _hiWeekdays : _mrWeekdays),
  };
}

Map<String, String> _pairs(List<String> english, List<String> local) =>
    {for (var i = 0; i < english.length; i++) english[i]: local[i]};

